/**
 * Writes the build network's stop places (`generated/stop-places.ts`) from its catalog and its
 * overrides (`lib/stop-places.ts`). `npm run refresh:stops` runs it after a refresh; run it alone
 * after changing the overrides:
 *
 *     npm run refresh:stop-places
 */
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { deriveStopPlaces } from "../src/lib/stop-places.ts";
import type { CatalogStop } from "../src/networks/network-definition.ts";
import { network } from "../src/networks/network.ts";

export async function writeStopPlaces(catalog: readonly CatalogStop[]): Promise<void> {
  const places = deriveStopPlaces(catalog, network.home.placeName, network.stopPlaceOverrides);
  const rows = Object.entries(places)
    .map(([id, place]) => `  ${JSON.stringify(id)}: ${JSON.stringify(place)},`)
    .join("\n");
  const module = `// Generated by scripts/write-stop-places.ts — do not edit by hand.
//
// From the stop catalog and \`stop-place-overrides.ts\`. Refresh with: npm run refresh:stop-places

import type { StopPlaceDefinition } from "../../network-definition";

export const stopPlaces: Readonly<Record<string, StopPlaceDefinition>> = {
${rows}
};
`;
  const path = new URL(`../src/networks/${network.id}/generated/stop-places.ts`, import.meta.url);
  await writeFile(path, module, "utf8");
  const joined = Object.values(places).filter(({ stopPoints }) => stopPoints.length > 1).length;
  console.log(`Wrote ${Object.keys(places).length} stop places (${joined} joining stop points)`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await writeStopPlaces(network.stopCatalog);
